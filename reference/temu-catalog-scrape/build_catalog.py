# Builds src/data/catalog.js from the scraped JSON in this folder. Run from the repo root: python3 reference/temu-catalog-scrape/build_catalog.py
import json, re, pathlib
src = pathlib.Path("reference/temu-catalog-scrape")
MAP = {
 "kitchen": ("Home & Kitchen", "Kitchen Utensils & Supplies", "kitchen gadgets"),
 "seasonal": ("Home & Kitchen", "Seasonal Decor", "christmas decorations"),
 "halloween": ("Home & Kitchen", "Seasonal Decor", "halloween decorations"),
 "home": ("Home & Kitchen", "Blankets & Throws", "throw blanket"),
 "womens": ("Women's Clothing", "Women's Sweaters", "womens sweater"),
 "mens": ("Men's Clothing", "Men's Hoodies & Sweatshirts", "mens hoodie"),
 "toys": ("Toys & Games", "Novelty & Gag Toys", "kids toys"),
 "beauty": ("Beauty & Personal Care", "Beauty Tools", "makeup brushes"),
 "electronics": ("Electronics", "Headphones & Earbuds", "wireless earbuds"),
 "pets": ("Pet Supplies", "Pet Toys", "dog toys"),
 "jewelry": ("Jewelry & Accessories", "Women's Jewelry", "womens earrings"),
 "auto": ("Automotive", "Interior Accessories", "car accessories"),
 "sports": ("Sports & Outdoors", "Sports & Outdoor Accessories", "yoga mat water bottle"),
 "office": ("Office & School Supplies", "Desk Organizers", "desk organizer school supplies"),
 "bags": ("Bags & Luggage", "Crossbody Bags & Totes", "crossbody bag"),
 "crafts": ("Arts, Crafts & Sewing", "Crochet & Knitting Kits", "crochet kit"),
}
out = []; ids = set()
for key, (cat, sub, q) in MAP.items():
    rows = json.loads((src / f"{key}.json").read_text())
    for n, (title, price, orig, sold, stars, tags, path) in enumerate(rows):
        if not price: continue
        title = re.sub(r"^\[[^\]]*\]\s*", "", title).strip(" ,-")
        iid = f"{key}-{n+1}"
        tags = [t for t in tags.split(",") if t]
        rating = stars if stars and stars <= 5 else None
        url = path if path.startswith("http") else "https://img.kwcdn.com/" + path
        o = dict(id=iid, img=url, localImg=f"/products/{iid}.jpg", name=title, category=cat, sub=sub,
                 price=float(price), sold=sold, rating=rating, tags=tags, local="Local" in tags,
                 shipsFrom="temu", sellerShipping=0, query=q)
        if orig and float(orig) > float(price): o["originalPrice"] = float(orig)
        out.append(o)
js = ("/**\n * GENERATED from reference/temu-catalog-scrape/*.json (Temu search results, collected Oct 31, 2026).\n"
      " * One search per category; titles shortened; prices, original prices, sold counts, star ratings and the\n"
      " * Local Warehouse / Last day / Best-selling tags are what Temu showed that day.\n"
      " * These fill out the store so it feels like Temu. The demo items stay in products.js.\n */\n"
      "export const catalog = " + json.dumps(out, indent=1, ensure_ascii=False) + ";\n")
pathlib.Path("src/data/catalog.js").write_text(js)
print(len(out), "items")

# --- category pages (Temu's own category listings) ---
import re as _re
cp = json.loads((src / "category-pages.json").read_text())
SUBS = {k: v["subs"] for k, v in cp.items() if not k.startswith("_")}
SUBS["Pet Supplies"] = ["Pet Furniture","Pet Cleaning","Pet Toys","Pet Beds & Bedding","Pet Apparel & Accessories","Bowls & Feeders","Fish, Reptiles & Amphibians","Pet Grooming","Pet Collars, Leashes & Harnesses","Pet Food & Treats","Carriers & Travel Products","Small Animals","Birds","Health Supplies","Training & Behavior"]
SUBS["Kids' Shoes"] = ["Girls' Boots","Girls' Sneakers","Boys' Sneakers","Girls' Sandals & Slippers","Boys' Athletic","Girls' Loafers & Slip-Ons","Boys' Boots","Baby Girl Shoes","Boys' Sandals & Slippers","Baby Boy Shoes","Girls' Athletic"]
seen = {o["img"] for o in out}
for cat, v in cp.items():
    if cat.startswith("_"): continue
    slug = _re.sub(r"[^a-z]+", "-", cat.lower()).strip("-")
    for n, (title, path, price, orig, sold, stars, wh, sub) in enumerate(v["g"]):
        url = "https://img.kwcdn.com/" + (path if path.startswith("local-goods-image/") else "product/" + path)
        if url in seen: continue
        seen.add(url)
        iid = f"cp-{slug}-{n+1}"
        o = dict(id=iid, img=url, localImg=f"/products/{iid}.jpg", name=title, category=cat, sub=sub, price=price,
                 sold=sold, rating=stars, tags=[], local=wh == 1, shipsFrom="temu", sellerShipping=0, query="")
        if orig and orig > price: o["originalPrice"] = orig
        out.append(o)
js = ("/**\n * GENERATED by reference/temu-catalog-scrape (gen script output; don't edit by hand).\n"
      " * Real Temu listings collected Oct 31, 2026: one search per category (search-name .json files) plus Temu's\n"
      " * own category pages (category-pages.json). Titles shortened; prices, original prices, sold counts, star\n"
      " * ratings, Local Warehouse and Last day tags are what Temu showed that day.\n"
      " * These fill out the store so it feels like Temu. The demo cart items stay in products.js.\n */\n"
      "export const catalog = " + json.dumps(out, indent=1, ensure_ascii=False) + ";\n\n"
      "/** Temu's real subcategory lists (from each category page's Category filter, Oct 31, 2026). */\n"
      "export const TEMU_SUBCATEGORIES = " + json.dumps(SUBS, indent=1, ensure_ascii=False) + ";\n")
pathlib.Path("src/data/catalog.js").write_text(js)
print(len(out), "items total")
